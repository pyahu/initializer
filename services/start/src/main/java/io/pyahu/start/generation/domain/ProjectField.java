package io.pyahu.start.generation.domain;

import java.util.Arrays;
import java.util.List;
import java.util.regex.Pattern;
import java.util.stream.Collectors;
import org.jspecify.annotations.Nullable;

/**
 * One field of a request, with its rule. The same definitions validate requests and describe the form.
 *
 * @param defaultValue absent when the default is derived from other fields
 */
public record ProjectField(
        String id, String description, @Nullable String defaultValue, Pattern pattern, int maxLength) {

    public static final ProjectField NAME = new ProjectField(
            "name",
            "Lowercase words joined by hyphens, such as orders or order-history.",
            "demo",
            Pattern.compile("[a-z][a-z0-9]*(-[a-z0-9]+)*"),
            50);

    public static final ProjectField GROUP = new ProjectField(
            "group",
            "The Gradle group: lowercase segments joined by dots.",
            "com.example",
            Pattern.compile("[a-z][a-z0-9_]*(\\.[a-z][a-z0-9_]*)*"),
            100);

    public static final ProjectField PACKAGE = new ProjectField(
            "package",
            "The base Java package. Defaults to the group followed by the name without hyphens.",
            null,
            GROUP.pattern(),
            150);

    public static final ProjectField DESCRIPTION = new ProjectField(
            "description",
            "One line for the README and the API contract.",
            "Demo service generated by the Pyahu Initializer",
            Pattern.compile("[\\p{L}\\p{N} .,:;!?()'/&+-]*"),
            200);

    public static final ProjectField ARCHITECTURE = new ProjectField(
            "architecture",
            "How the code inside each capability is arranged.",
            Architecture.DEFAULT.id(),
            Pattern.compile(
                    Arrays.stream(Architecture.values()).map(Architecture::id).collect(Collectors.joining("|"))),
            20);

    public static final List<ProjectField> ALL = List.of(NAME, GROUP, PACKAGE, DESCRIPTION, ARCHITECTURE);
}
