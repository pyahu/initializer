package io.pyahu.start.generation.domain;

import java.util.List;
import java.util.regex.Pattern;
import java.util.stream.Collectors;
import org.jspecify.annotations.Nullable;

/**
 * One field of a request, with its rule. The same definitions validate requests and describe the form.
 *
 * @param defaultValue absent when the default is derived from other fields
 * @param choices the values a field with a fixed list accepts, empty for free text
 */
public record ProjectField(
        String id,
        String description,
        @Nullable String defaultValue,
        Pattern pattern,
        int maxLength,
        List<Choice> choices) {

    public ProjectField {
        choices = List.copyOf(choices);
    }

    public static final ProjectField NAME = text(
            "name",
            "Lowercase words joined by hyphens, such as orders or order-history.",
            "demo",
            "[a-z][a-z0-9]*(-[a-z0-9]+)*",
            50);

    public static final ProjectField GROUP = text(
            "group",
            "The Gradle group: lowercase segments joined by dots.",
            "com.example",
            "[a-z][a-z0-9_]*(\\.[a-z][a-z0-9_]*)*",
            100);

    public static final ProjectField PACKAGE = text(
            "package",
            "The base Java package. Defaults to the group followed by the name without hyphens.",
            null,
            GROUP.pattern().pattern(),
            150);

    public static final ProjectField DESCRIPTION = text(
            "description",
            "One line for the README and the API contract.",
            "Demo service generated by the Pyahu Initializer",
            "[\\p{L}\\p{N} .,:;!?()'/&+-]*",
            200);

    public static final ProjectField ARCHITECTURE = choice(
            "architecture",
            "How the code inside each capability is arranged.",
            Architecture.DEFAULT,
            Architecture.values());

    public static final ProjectField DATABASE = choice(
            "database",
            "PostgreSQL with migrations in a Job and two database roles. Default none.",
            Database.NONE,
            Database.values());

    public static final ProjectField AUTH = choice(
            "auth",
            "OpenID Connect: the service accepts only tokens for its API; the frontend, if any, logs users in.",
            Auth.NONE,
            Auth.values());

    public static final ProjectField FRONTEND = choice(
            "frontend",
            "A Next.js frontend in frontends/web, with its own image and Deployment.",
            Frontend.NONE,
            Frontend.values());

    public static final List<ProjectField> ALL =
            List.of(NAME, GROUP, PACKAGE, DESCRIPTION, ARCHITECTURE, DATABASE, AUTH, FRONTEND);

    private static ProjectField text(
            String id, String description, @Nullable String defaultValue, String pattern, int maxLength) {
        return new ProjectField(id, description, defaultValue, Pattern.compile(pattern), maxLength, List.of());
    }

    private static ProjectField choice(String id, String description, Choice defaultValue, Choice... choices) {
        List<Choice> all = List.of(choices);
        Pattern pattern = Pattern.compile(all.stream().map(Choice::id).collect(Collectors.joining("|")));
        int maxLength = all.stream().mapToInt(c -> c.id().length()).max().orElse(0);
        return new ProjectField(id, description, defaultValue.id(), pattern, maxLength, all);
    }
}
